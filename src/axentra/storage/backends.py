"""Object storage backends: where file bytes live.

:class:`StorageBackend` is a small interface over a flat key space. Keys are generated by the
storage service from ids only (``<product_id>/<tenant_id>/<file_id>``) and validated by every
backend (:func:`check_key`), so user input can never select a path.

- :class:`LocalBackend` writes below one directory: temp file (``O_CREAT|O_EXCL``, mode 0600) in the
  target directory, ``fsync``, atomic ``rename``, directory ``fsync``. Reads refuse symlinks.
- :class:`S3Backend` uses boto3 (optional extra ``axentra[s3]``, imported lazily); uploads stream
  through a multipart upload in 8 MiB parts (single ``PutObject`` for small objects) and abort the
  multipart upload when the source stream fails (e.g. the size limit is hit).
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Iterable, Iterator
import contextlib
import errno
import logging
import os
from pathlib import Path
import re
import secrets
import time
from typing import TYPE_CHECKING, Any

from axentra.core.errors import ConfigurationError, NotFound

if TYPE_CHECKING:
    from axentra.config.settings import StorageSettings

logger = logging.getLogger(__name__)

_KEY = re.compile(r"^[A-Za-z0-9_-]{1,128}(/[A-Za-z0-9_-]{1,128}){0,7}$")
CHUNK_SIZE = 64 * 1024
TEMP_PREFIX = ".tmp-"


class ObjectNotFound(NotFound):
    """The backend holds no object under the key."""


def check_key(key: str) -> str:
    """Keys are slash-separated segments of ``[A-Za-z0-9_-]``: no dots, no traversal, no absolute paths."""
    if not isinstance(key, str) or not _KEY.match(key):
        raise ValueError("invalid storage key")
    return key


class StorageBackend(ABC):
    """Minimal object storage interface. Implementations must be safe to use from several threads."""

    name: str = "abstract"

    @abstractmethod
    def put(self, key: str, chunks: Iterable[bytes], *, content_type: str) -> None:
        """Store the stream under ``key``, replacing an existing object atomically.

        If iterating ``chunks`` raises, nothing is left behind and the exception propagates.
        """

    @abstractmethod
    def get(self, key: str, *, chunk_size: int = CHUNK_SIZE) -> Iterator[bytes]:
        """Stream the object. Raises :class:`ObjectNotFound` before yielding when it is missing."""

    @abstractmethod
    def delete(self, key: str) -> bool:
        """Delete the object; idempotent. Returns whether an object existed (best effort for S3)."""

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def list_keys(self, prefix: str = "") -> Iterator[str]:
        """All keys starting with ``prefix`` (used by the orphan purge)."""

    def presigned_url(
        self, key: str, *, ttl_seconds: int, filename_header: str, content_type: str
    ) -> str | None:
        """A direct, time-limited download URL, or None when the backend cannot issue one."""
        return None

    def cleanup_temporary(self, older_than_seconds: int = 3600) -> int:
        """Remove leftovers of interrupted writes; returns how many were removed."""
        return 0


class LocalBackend(StorageBackend):
    name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _ensure_root(self) -> None:
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        check_key(key)
        path = self.root.joinpath(*key.split("/"))
        # Defense in depth against symlinked directories inside the root.
        real_parent = Path(os.path.realpath(path.parent))
        if os.path.commonpath([real_parent, self.root]) != str(self.root):
            raise ValueError("storage key resolves outside the storage root")
        return path

    def put(self, key: str, chunks: Iterable[bytes], *, content_type: str) -> None:
        self._ensure_root()
        check_key(key)
        parent = self.root
        for segment in key.split("/")[:-1]:
            parent = parent / segment
            parent.mkdir(mode=0o700, exist_ok=True)
        path = self._path(key)
        tmp = path.parent / f"{TEMP_PREFIX}{secrets.token_hex(8)}"
        flags = (
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0)
        )
        fd = os.open(tmp, flags, 0o600)
        try:
            with os.fdopen(fd, "wb") as fh:
                for chunk in chunks:
                    fh.write(chunk)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, path)
        except BaseException:
            with contextlib.suppress(FileNotFoundError):
                tmp.unlink()
            raise
        self._fsync_dir(path.parent)

    @staticmethod
    def _fsync_dir(directory: Path) -> None:
        try:
            dfd = os.open(directory, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
        except OSError:  # pragma: no cover - platforms without directory fds
            return
        try:
            os.fsync(dfd)
        except OSError:  # pragma: no cover
            pass
        finally:
            os.close(dfd)

    def get(self, key: str, *, chunk_size: int = CHUNK_SIZE) -> Iterator[bytes]:
        path = self._path(key)
        try:
            fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0))
        except FileNotFoundError:
            raise ObjectNotFound("object not found") from None
        except OSError as exc:
            if exc.errno == errno.ELOOP:
                raise ObjectNotFound("object not found") from None
            raise
        fh = os.fdopen(fd, "rb")

        def stream() -> Iterator[bytes]:
            with fh:
                while True:
                    block = fh.read(chunk_size)
                    if not block:
                        return
                    yield block

        return stream()

    def delete(self, key: str) -> bool:
        path = self._path(key)
        try:
            path.unlink()
        except FileNotFoundError:
            return False
        self._fsync_dir(path.parent)
        return True

    def exists(self, key: str) -> bool:
        path = self._path(key)
        return path.is_file() and not path.is_symlink()

    def list_keys(self, prefix: str = "") -> Iterator[str]:
        if not self.root.is_dir():
            return
        for dirpath, dirnames, filenames in os.walk(self.root, followlinks=False):
            dirnames[:] = [d for d in dirnames if not d.startswith(".")]
            rel = Path(dirpath).relative_to(self.root)
            for fname in filenames:
                if fname.startswith("."):
                    continue
                key = "/".join([*rel.parts, fname])
                if key.startswith(prefix) and _KEY.match(key):
                    yield key

    def cleanup_temporary(self, older_than_seconds: int = 3600) -> int:
        if not self.root.is_dir():
            return 0
        cutoff = time.time() - older_than_seconds
        removed = 0
        for dirpath, _dirs, filenames in os.walk(self.root, followlinks=False):
            for fname in filenames:
                if not fname.startswith(TEMP_PREFIX):
                    continue
                p = Path(dirpath) / fname
                try:
                    if p.lstat().st_mtime < cutoff:
                        p.unlink()
                        removed += 1
                except FileNotFoundError:
                    continue
        return removed


PART_SIZE = 8 * 1024 * 1024


class S3Backend(StorageBackend):
    """Amazon S3 or an S3-compatible service (MinIO, Ceph, R2, ...)."""

    name = "s3"

    def __init__(
        self,
        bucket: str,
        *,
        region: str | None = None,
        endpoint_url: str | None = None,
        access_key: str | None = None,
        secret_key: str | None = None,
        prefix: str = "",
        server_side_encryption: str | None = None,
        client: Any = None,
    ) -> None:
        if not bucket:
            raise ConfigurationError("storage.s3_bucket is required for the s3 backend")
        if prefix and not _KEY.match(prefix.rstrip("/")):
            raise ConfigurationError("invalid S3 key prefix")
        self.bucket = bucket
        self.prefix = prefix.rstrip("/") + "/" if prefix else ""
        self.sse = server_side_encryption
        if client is None:
            try:
                import boto3
            except ImportError as exc:  # pragma: no cover - depends on installed extras
                raise ConfigurationError(
                    "the s3 storage backend needs boto3: pip install 'axentra[s3]'"
                ) from exc
            client = boto3.client(
                "s3",
                region_name=region,
                endpoint_url=endpoint_url,
                aws_access_key_id=access_key,
                aws_secret_access_key=secret_key,
            )
        self.client = client

    def _k(self, key: str) -> str:
        return self.prefix + check_key(key)

    def _extra(self, content_type: str) -> dict[str, Any]:
        extra: dict[str, Any] = {"ContentType": content_type}
        if self.sse:
            extra["ServerSideEncryption"] = self.sse
        return extra

    def put(self, key: str, chunks: Iterable[bytes], *, content_type: str) -> None:
        k = self._k(key)
        buf = bytearray()
        upload_id: str | None = None
        parts: list[dict[str, Any]] = []
        try:
            for chunk in chunks:
                buf += chunk
                while len(buf) >= PART_SIZE:
                    if upload_id is None:
                        upload_id = self.client.create_multipart_upload(
                            Bucket=self.bucket, Key=k, **self._extra(content_type)
                        )["UploadId"]
                    part = bytes(buf[:PART_SIZE])
                    del buf[:PART_SIZE]
                    n = len(parts) + 1
                    resp = self.client.upload_part(
                        Bucket=self.bucket, Key=k, UploadId=upload_id, PartNumber=n, Body=part
                    )
                    parts.append({"ETag": resp["ETag"], "PartNumber": n})
            if upload_id is None:
                self.client.put_object(
                    Bucket=self.bucket, Key=k, Body=bytes(buf), **self._extra(content_type)
                )
                return
            if buf:
                n = len(parts) + 1
                resp = self.client.upload_part(
                    Bucket=self.bucket, Key=k, UploadId=upload_id, PartNumber=n, Body=bytes(buf)
                )
                parts.append({"ETag": resp["ETag"], "PartNumber": n})
            self.client.complete_multipart_upload(
                Bucket=self.bucket, Key=k, UploadId=upload_id, MultipartUpload={"Parts": parts}
            )
        except BaseException:
            if upload_id is not None:
                try:
                    self.client.abort_multipart_upload(Bucket=self.bucket, Key=k, UploadId=upload_id)
                except Exception:
                    logger.warning("could not abort S3 multipart upload for %s", k, exc_info=True)
            raise

    @staticmethod
    def _is_missing(exc: Exception) -> bool:
        resp = getattr(exc, "response", None) or {}
        code = str(resp.get("Error", {}).get("Code", ""))
        return code in ("NoSuchKey", "404", "NotFound")

    def get(self, key: str, *, chunk_size: int = CHUNK_SIZE) -> Iterator[bytes]:
        try:
            obj = self.client.get_object(Bucket=self.bucket, Key=self._k(key))
        except Exception as exc:
            if self._is_missing(exc):
                raise ObjectNotFound("object not found") from None
            raise
        body = obj["Body"]

        def stream() -> Iterator[bytes]:
            try:
                yield from body.iter_chunks(chunk_size)
            finally:
                body.close()

        return stream()

    def delete(self, key: str) -> bool:
        existed = self.exists(key)
        self.client.delete_object(Bucket=self.bucket, Key=self._k(key))
        return existed

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._k(key))
        except Exception as exc:
            if self._is_missing(exc):
                return False
            raise
        return True

    def list_keys(self, prefix: str = "") -> Iterator[str]:
        paginator = self.client.get_paginator("list_objects_v2")
        for page in paginator.paginate(Bucket=self.bucket, Prefix=self.prefix + prefix):
            for item in page.get("Contents", []) or []:
                key = str(item["Key"])[len(self.prefix) :]
                if _KEY.match(key):
                    yield key

    def presigned_url(
        self, key: str, *, ttl_seconds: int, filename_header: str, content_type: str
    ) -> str | None:
        url: str = self.client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": self.bucket,
                "Key": self._k(key),
                "ResponseContentDisposition": filename_header,
                "ResponseContentType": content_type,
            },
            ExpiresIn=ttl_seconds,
        )
        return url


def backend_from_settings(cfg: StorageSettings) -> StorageBackend:
    if cfg.backend == "s3":
        from axentra.config.secrets import resolve_secret

        return S3Backend(
            cfg.s3_bucket,
            region=cfg.s3_region,
            endpoint_url=cfg.s3_endpoint_url,
            access_key=resolve_secret(cfg.s3_access_key_ref) if cfg.s3_access_key_ref else None,
            secret_key=resolve_secret(cfg.s3_secret_key_ref) if cfg.s3_secret_key_ref else None,
            prefix=cfg.s3_prefix,
            server_side_encryption=cfg.s3_server_side_encryption,
        )
    return LocalBackend(cfg.local_path)
