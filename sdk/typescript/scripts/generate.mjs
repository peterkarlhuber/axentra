#!/usr/bin/env node
/**
 * Regenerates the SDK's generated sources from the COMMITTED OpenAPI contract
 * (../../openapi/axentra-v1.json), never from a running server:
 *
 *   src/schema.d.ts   types of every path, operation and component (openapi-typescript)
 *   src/generated.ts  the API version the SDK was generated for + the contract's SHA-256
 *
 *   npm run generate           write both files
 *   npm run generate:check     exit 1 when the committed files are stale (CI)
 *
 * Env: AXENTRA_OPENAPI overrides the contract path (for experiments; CI uses the default).
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contract = path.resolve(root, process.env.AXENTRA_OPENAPI ?? '../../openapi/axentra-v1.json');
const check = process.argv.includes('--check');

const text = fs.readFileSync(contract, 'utf8');
const spec = JSON.parse(text);
const match = /^(\d+)\.(\d+)$/.exec(String(spec.info?.version ?? ''));
if (!match) throw new Error(`${contract}: info.version must be "<major>.<minor>", got ${spec.info?.version}`);
const sha256 = createHash('sha256').update(text).digest('hex');

const schema = astToString(await openapiTS(spec, { alphabetize: true, defaultNonNullable: false }));
const generated = `// Generated by scripts/generate.mjs from openapi/axentra-v1.json. Do not edit.

/** The Axentra HTTP API version this SDK build was generated for (\`info.version\`). */
export const GENERATED_API_VERSION = { major: ${Number(match[1])}, minor: ${Number(match[2])} } as const;

/** SHA-256 of the OpenAPI document the types were generated from. */
export const GENERATED_FROM_SHA256 = '${sha256}';
`;

const outputs = {
  'src/schema.d.ts': `/**\n * Generated by openapi-typescript from openapi/axentra-v1.json (scripts/generate.mjs).\n * Do not edit; run \`npm run generate\`.\n */\n\n${schema}`,
  'src/generated.ts': generated,
};

let stale = false;
for (const [rel, content] of Object.entries(outputs)) {
  const file = path.join(root, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current !== content) {
      console.error(`${rel} is out of date with ${path.relative(root, contract)}; run \`npm run generate\``);
      stale = true;
    }
  } else if (current !== content) {
    fs.writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  } else {
    console.log(`${rel} is up to date`);
  }
}
if (check && !stale) console.log('generated sources are up to date');
process.exit(stale ? 1 : 0);
