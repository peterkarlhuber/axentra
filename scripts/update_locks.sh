#!/usr/bin/env bash
# Regenerate the hash-pinned locks of the container image from pyproject.toml and deploy/constraints.txt.
# Needs uv (https://docs.astral.sh/uv/) and curl. Run after changing dependencies, deploy/constraints.txt or
# requirements/tabrion.txt, then commit deploy/locks/*.txt together with that change (CI runs
# scripts/check_locks.py).
#
# Tabrion is not on a package index (TABRION VER-1, V-B0): requirements/tabrion.txt tells uv where the pinned commit
# is, and Tabrion itself is left out of server.txt and full.txt. deploy/locks/tabrion.txt pins the source archive of
# that commit by hash instead; the image builds its wheel offline with the hatchling of build.txt (TABRION MIG-AXE-3).
set -euo pipefail
cd "$(dirname "$0")/.."
common=(--python-version 3.13 --python-platform x86_64-manylinux_2_28 --no-header --no-annotate --generate-hashes --quiet)
tabrion=(requirements/tabrion.txt --no-emit-package tabrion)
uv pip compile pyproject.toml "${tabrion[@]}" --extra server -c deploy/constraints.txt "${common[@]}" \
  -o deploy/locks/server.txt
uv pip compile pyproject.toml "${tabrion[@]}" --extra server --extra oidc --extra s3 --extra otel \
  -c deploy/constraints.txt "${common[@]}" -o deploy/locks/full.txt
uv pip compile deploy/locks/build.in "${common[@]}" -o deploy/locks/build.txt
sha="$(grep -oE '^tabrion @ git\+https://github\.com/peterkarlhuber/tabrion\.git@[0-9a-f]{40}$' requirements/tabrion.txt \
  | grep -oE '[0-9a-f]{40}$')"
url="https://github.com/peterkarlhuber/tabrion/archive/${sha}.tar.gz"
digest="$(curl -fsSL --retry 3 "${url}" | sha256sum | cut -d' ' -f1)"
cat > deploy/locks/tabrion.txt <<LOCK
# Tabrion for the container image: the source archive of the commit that requirements/tabrion.txt pins, by hash.
# Generated by scripts/update_locks.sh; the Dockerfile builds the wheel offline with the hatchling of build.txt.
tabrion @ ${url} \\
    --hash=sha256:${digest}
LOCK
python3 scripts/check_locks.py
